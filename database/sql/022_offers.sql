BEGIN;

CREATE TABLE IF NOT EXISTS offers (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  restaurant_id INT NOT NULL,
  title VARCHAR(160) NOT NULL,
  description VARCHAR(500) NOT NULL DEFAULT '',
  image_url VARCHAR(500) NULL,
  offer_type VARCHAR(30) NOT NULL,
  original_price DECIMAL(12,2) NOT NULL DEFAULT 0,
  offer_price DECIMAL(12,2) NOT NULL,
  discount_value DECIMAL(12,2) NOT NULL DEFAULT 0,
  discount_type VARCHAR(20) NOT NULL DEFAULT 'fixed',
  minimum_order_amount DECIMAL(12,2) NOT NULL DEFAULT 0,
  maximum_discount DECIMAL(12,2) NULL,
  coupon_code VARCHAR(40) NULL,
  start_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  expires_at TIMESTAMP NULL,
  usage_limit INT NULL,
  per_customer_limit INT NULL,
  usage_count INT NOT NULL DEFAULT 0,
  status VARCHAR(20) NOT NULL DEFAULT 'active',
  allow_stacking BOOLEAN NOT NULL DEFAULT FALSE,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_offers_restaurant FOREIGN KEY (restaurant_id) REFERENCES restaurants(id) ON DELETE CASCADE,
  CONSTRAINT chk_offers_type CHECK (offer_type IN ('combo', 'percentage', 'flat', 'bogo', 'free_item', 'special_price')),
  CONSTRAINT chk_offers_discount_type CHECK (discount_type IN ('percent', 'fixed')),
  CONSTRAINT chk_offers_status CHECK (status IN ('active', 'paused')),
  CONSTRAINT chk_offers_prices CHECK (original_price >= 0 AND offer_price >= 0 AND offer_price <= original_price),
  CONSTRAINT chk_offers_dates CHECK (expires_at IS NULL OR expires_at > start_at),
  CONSTRAINT chk_offers_limits CHECK (
    (usage_limit IS NULL OR usage_limit > 0) AND
    (per_customer_limit IS NULL OR per_customer_limit > 0)
  )
);

CREATE TABLE IF NOT EXISTS offer_items (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  offer_id INT NOT NULL,
  menu_item_id INT NOT NULL,
  item_name_snapshot VARCHAR(120) NOT NULL,
  quantity INT NOT NULL,
  price_snapshot DECIMAL(12,2) NOT NULL,
  is_reward_item BOOLEAN NOT NULL DEFAULT FALSE,
  CONSTRAINT fk_offer_items_offer FOREIGN KEY (offer_id) REFERENCES offers(id) ON DELETE CASCADE,
  CONSTRAINT fk_offer_items_menu FOREIGN KEY (menu_item_id) REFERENCES menu_items(id) ON DELETE RESTRICT,
  CONSTRAINT chk_offer_items_quantity CHECK (quantity > 0),
  CONSTRAINT chk_offer_items_price CHECK (price_snapshot >= 0)
);

CREATE TABLE IF NOT EXISTS offer_redemptions (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  offer_id INT NOT NULL,
  restaurant_id INT NOT NULL,
  customer_id INT NULL,
  order_id INT NOT NULL UNIQUE,
  discount_amount DECIMAL(12,2) NOT NULL,
  redeemed_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_offer_redemptions_offer FOREIGN KEY (offer_id) REFERENCES offers(id) ON DELETE CASCADE,
  CONSTRAINT fk_offer_redemptions_restaurant FOREIGN KEY (restaurant_id) REFERENCES restaurants(id) ON DELETE CASCADE,
  CONSTRAINT fk_offer_redemptions_order FOREIGN KEY (order_id) REFERENCES orders(id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_offers_public
  ON offers (restaurant_id, status, start_at, expires_at);
CREATE INDEX IF NOT EXISTS idx_offer_items_offer ON offer_items (offer_id);
CREATE INDEX IF NOT EXISTS idx_offer_redemptions_offer ON offer_redemptions (offer_id, redeemed_at DESC);

DROP TRIGGER IF EXISTS trg_offers_updated_at ON offers;
CREATE TRIGGER trg_offers_updated_at
BEFORE UPDATE ON offers
FOR EACH ROW EXECUTE PROCEDURE set_updated_at();

INSERT INTO schema_migrations (version)
VALUES ('022_offers')
ON CONFLICT (version) DO NOTHING;

COMMIT;
